'use strict';

const { AppError } = require('../../../../shared/errors');
const { ID_RE } = require('../../../../shared/ids');
const { newId, safeEqual } = require('../../../../shared/crypto');
const { MAX_TEXT_LENGTH, SESSION_RE, webContact } = require('../../domain/inbound');
const { bucketsFor } = require('../../domain/limits');

/**
 * Web chat: the page sends a message (or just polls) and gets the replies queued since last time.
 *   - real insurers need their web chat key; demo insurers accept keyless chat; others refuse
 *   - the visitor is identified by a random session id generated by the page
 *   - documents sent back (e.g. the policy) are given as short-lived signed links
 *   - every request counts against abuse limits (domain/limits.js) before any AI call
 * Errors are stable codes; the interface turns them into HTTP answers.
 */
function makeWebChat({ tenants, handleInbound, store, uploads, customerIds, rateLimiter }) {
  return async function webChat({ tenantId, key, sessionId, text, attachments, messageId, poll, clientIp }) {
    const loaded = await tenants.load(tenantId);
    if (!loaded) throw new AppError('not-found', 'UNKNOWN_TENANT');
    const { tenant } = loaded;
    if (tenant.webchatKey) {
      if (!safeEqual(key, tenant.webchatKey)) throw new AppError('unauthenticated', 'BAD_KEY');
    } else if (!tenant.demo) {
      throw new AppError('permission-denied', 'WEBCHAT_NOT_ENABLED');
    }
    if (typeof sessionId !== 'string' || !SESSION_RE.test(sessionId)) throw new AppError('invalid-argument', 'BAD_SESSION');
    const from = webContact(sessionId);
    const sessionKey = customerIds.keyFor(from);

    if (rateLimiter) {
      const ipKey = clientIp ? customerIds.keyFor(`ip:${clientIp}`) : null; // IPs are pseudonymized too
      const verdict = await rateLimiter.consume(bucketsFor({ kind: poll ? 'poll' : 'message', tenantId, sessionKey, ipKey }));
      if (!verdict.allowed) throw new AppError('resource-exhausted', 'RATE_LIMITED', { retryAfterSec: verdict.retryAfterSec });
    }

    if (!poll) {
      if (typeof text !== 'string' || text.length > MAX_TEXT_LENGTH) throw new AppError('invalid-argument', 'BAD_TEXT');
      if (messageId !== undefined && !ID_RE.test(messageId)) throw new AppError('invalid-argument', 'BAD_MESSAGE_ID');
      const files = (Array.isArray(attachments) ? attachments : []).map((a) => ({
        mimeType: a.mimeType, filename: a.filename, demoFixture: a.demoFixture,
        data: typeof a.dataBase64 === 'string' ? Buffer.from(a.dataBase64, 'base64') : undefined,
      }));
      await handleInbound({ tenantId, ...loaded, inbound: { messageId: messageId || newId(), from, text, attachments: files, channel: 'web' } });
    }

    const pending = await store.takePendingWebMessages(tenantId, sessionKey);
    const messages = [];
    for (const m of pending) {
      if (m.kind === 'document') {
        messages.push({ kind: 'document', filename: m.document.filename, url: await uploads.getSignedUrl(m.document.path, 15 * 60 * 1000), text: m.text || null });
      } else {
        messages.push({ kind: 'text', text: m.text });
      }
    }
    return { messages };
  };
}

module.exports = { makeWebChat };
